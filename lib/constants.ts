/**
 * 日本人・月給制の欠勤控除を開始する月（2026-08-31 代表決定）
 *
 * 新卒＝入社1年目は月給制（docs/wage-system.md 第13節）だが、従来は
 * **出勤日数に関わらず月給が固定**で、欠勤しても控除されない実装だった。
 * 欠勤控除を入れることにしたが、遡って適用すると支給済みの過去分と食い違うため、
 * この月以降の給与計算にだけ効かせる。

 * 2026-08-31: **2026年8月分から**適用（代表決定）。8月分は9月25日支給でまだ確定前。
 * 6〜7月分（支給済み）は従来どおり控除なし。
 * 欠勤日数は「出面に記録された欠勤」だけを数える（現場カレンダーから引かない）。
 * docs/salary-calculation.md 参照。
 *
 * 1日あたりの控除額 = 月給 ÷ 月平均所定労働時間(145h) × 1日の所定労働時間(7h)
 * ＝ 残業単価と同じ分母を使う（就業規則の整合が取りやすい）。
 */
export const JP_MONTHLY_ABSENCE_DEDUCTION_FROM_YM = '202608'

/**
 * 日本人・月給制の欠勤控除に使う **年間所定労働日数**（2026-08-31 代表決定）
 *
 * 年間休日115日（docs/wage-system.md 第13節の新卒の想定）→ 365 − 115 = 250日。
 * 1日あたりの控除額 = 月給 ÷ (この日数 ÷ 12) = 月給 ÷ 20.83日。
 *
 * ⚠️ **月ごとの所定日数で割ってはいけない。** 同じ1日の欠勤でも
 * 7月(22日所定)は10,681円、8月(16日所定)は14,687円と金額が変わってしまい、
 * 稼働日の少ない月に休むほど損をする不公平が生じる。
 *
 * ⚠️ **残業単価の分母 145h（JP_SALARY_AVG_MONTHLY_HOURS）を流用してはいけない。**
 * 145h は 250日 × 7h ÷ 12 = 145.83h を**安全側に切り下げた**値で、
 * 「分母を小さくして単価を上げる」＝社員に有利な方向の調整。控除に使うと
 * 同じ調整が「控除を増やす」＝社員に不利な方向へ反転する。
 * 割増単価は丸めた値、控除は丸めない値、と使い分けるのが正しい。
 */
export const JP_ANNUAL_WORK_DAYS = 250

/** 月平均所定労働日数（= 年間所定 ÷ 12）。欠勤控除の分母。 */
export const JP_AVG_MONTHLY_WORK_DAYS = JP_ANNUAL_WORK_DAYS / 12

